def make(rng: random.Random, spec: str | None = None) -> dict:
    spec = spec or rng.choice(list(SPEC_INTRO))
    from app.ingredients import SPECIALIZATIONS
    own = SPECIALIZATIONS[spec]["ingredients"]
    k = rng.choice([1, 2, 2, 3, 3, 4])
    key = rng.sample(own, k)
    # иногда работодатель заказывает навык «чужой» группы (бэкенду — SQL-оконки и т.п.)
    if rng.random() < 0.12:
        other = [i for i in ING_PHRASES if i not in own]
        key.append(rng.choice(other))
    grade = rng.choice(["intern", "junior", "middle", "middle", "senior", "senior"])
    stack = rng.choice(SPEC_STACKS[spec])
    parts = []
    intro = rng.choice(SPEC_INTRO[spec]).format(stack=stack)
    if rng.random() < 0.6:
        intro += f" ({rng.choice(GRADE_PHR[grade])})" if rng.random() < 0.5 else f" уровня {rng.choice(GRADE_PHR[grade])}"
        grade_in_text = True
    else:
        grade_in_text = False
    parts.append(intro + ".")
    phrases = []
    for ing in key:
        phrases += rng.sample(ING_PHRASES[ing], rng.choice([1, 1, 2]))
    rng.shuffle(phrases)
    if rng.random() < 0.5:
        parts.append(rng.choice(STARTS) + ", ".join(phrases) + ".")
    else:
        for ph in phrases:
            cap = ph[0].upper() + ph[1:] if len(ph) > 1 and ph[1].islower() else ph
            parts.append(rng.choice(STARTS) + cap + ".")
    st = rng.sample(SPEC_STACKS[spec], rng.randint(1, 3))
    parts.append(rng.choice(["Стек: ", "Технологии: ", "Используем ", "Наш стек — "]) + ", ".join(st) + ".")
    if not grade_in_text:
        parts.append(rng.choice(["Ждём кандидата уровня ", "Уровень: ", "Требования: ", ""]) + rng.choice(GRADE_PHR[grade]) + ".")
    for noise in rng.sample(NOISE, rng.randint(0, 2)):
        parts.insert(rng.randint(1, len(parts)), noise)
    parts.append(rng.choice(FORMATS))
    if rng.random() < 0.4:
        lo = rng.choice([60, 90, 120, 150, 180, 220, 260, 300, 350])
        parts.append(f"{lo}-{lo + rng.choice([40, 60, 80, 100])} тыс.")
    text = " ".join(p for p in parts if p).replace("..", ".")
    return {"text": text, "specialization": spec, "grade": grade, "ingredients": key}


def corpus(n: int, seed: int = 0) -> list[dict]:
    rng = random.Random(seed)
    return [make(rng) for _ in range(n)]
